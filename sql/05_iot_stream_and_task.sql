-- 1. Track new JSON payloads arriving in RAW.IOT_TELEMETRY
CREATE OR REPLACE STREAM ATMOSYNC_DB.RAW.IOT_TELEMETRY_STREAM
ON TABLE ATMOSYNC_DB.RAW.IOT_TELEMETRY
APPEND_ONLY = TRUE;

-- 2. Automatically flatten new stream rows into ANALYTICS every 1 minute
CREATE OR REPLACE TASK ATMOSYNC_DB.ANALYTICS.TASK_PROCESS_IOT_TELEMETRY
  WAREHOUSE = COMPUTE_WH
  SCHEDULE = '1 MINUTE'
WHEN
  SYSTEM$STREAM_HAS_DATA('ATMOSYNC_DB.RAW.IOT_TELEMETRY_STREAM')
AS
INSERT INTO ATMOSYNC_DB.ANALYTICS.IOT_MICROCLIMATE_CLEAN
SELECT
    RAW_PAYLOAD:sensor_id::STRING,
    UPPER(TRIM(RAW_PAYLOAD:market::STRING)),
    RAW_PAYLOAD:recorded_at::TIMESTAMP_NTZ,
    DATE(RAW_PAYLOAD:recorded_at::TIMESTAMP_NTZ),
    RAW_PAYLOAD:temp_c::FLOAT,
    RAW_PAYLOAD:humidity_pct::FLOAT,
    RAW_PAYLOAD:storage_zone::STRING,
    INGESTED_AT
FROM ATMOSYNC_DB.RAW.IOT_TELEMETRY_STREAM;

-- 3. Start the automated task
ALTER TASK ATMOSYNC_DB.ANALYTICS.TASK_PROCESS_IOT_TELEMETRY RESUME;