CREATE OR REPLACE TABLE ATMOSYNC_DB.ANALYTICS.TOMATO_MARKET_DAILY AS
SELECT DISTINCT
    ARRIVAL_DATE,
    UPPER(TRIM(STATE)) AS STATE,
    UPPER(TRIM(DISTRICT)) AS DISTRICT,
    UPPER(TRIM(MARKET)) AS MARKET,
    UPPER(TRIM(VARIETY)) AS VARIETY,
    UPPER(TRIM(GRADE)) AS GRADE,
    MIN_PRICE,
    MODAL_PRICE,
    MAX_PRICE,
    ROUND(MAX_PRICE - MIN_PRICE, 2) AS DAILY_PRICE_SPREAD,
    ROUND(((MAX_PRICE - MIN_PRICE) / NULLIF(MODAL_PRICE, 0)) * 100, 2) AS VOLATILITY_PCT
FROM ATMOSYNC_DB.RAW.TOMATO_PRICES
WHERE MODAL_PRICE IS NOT NULL
  AND MODAL_PRICE > 0;



  SELECT 
    MIN(ARRIVAL_DATE) AS START_DATE,
    MAX(ARRIVAL_DATE) AS END_DATE,
    COUNT(*) AS CLEAN_ROWS,
    COUNT(DISTINCT MARKET) AS TOTAL_MARKETS,
    ROUND(AVG(MODAL_PRICE), 2) AS AVG_MODAL_PRICE
FROM ATMOSYNC_DB.ANALYTICS.TOMATO_MARKET_DAILY;