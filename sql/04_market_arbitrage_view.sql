CREATE OR REPLACE VIEW ATMOSYNC_DB.ANALYTICS.MARKET_ARBITRAGE_MICROCLIMATE AS
SELECT
    p.ARRIVAL_DATE,
    p.STATE,
    p.DISTRICT,
    p.MARKET,
    p.VARIETY,
    p.GRADE,
    p.MIN_PRICE,
    p.MODAL_PRICE,
    p.MAX_PRICE,
    p.DAILY_PRICE_SPREAD,
    p.VOLATILITY_PCT,
    i.SENSOR_ID,
    i.STORAGE_ZONE,
    i.TEMP_C,
    i.HUMIDITY_PCT,
    CASE
        WHEN i.TEMP_C >= 32.0 AND p.VOLATILITY_PCT >= 25.0 THEN 'HIGH_HEAT_ARBITRAGE_RISK'
        WHEN p.DAILY_PRICE_SPREAD >= 500 THEN 'HIGH_SPREAD_OPPORTUNITY'
        ELSE 'NORMAL'
    END AS ARBITRAGE_SIGNAL
FROM ATMOSYNC_DB.ANALYTICS.TOMATO_MARKET_DAILY p
LEFT JOIN ATMOSYNC_DB.ANALYTICS.IOT_MICROCLIMATE_CLEAN i
    ON p.MARKET = i.MARKET
   AND p.ARRIVAL_DATE = i.READING_DATE;

SELECT *
FROM ATMOSYNC_DB.ANALYTICS.MARKET_ARBITRAGE_MICROCLIMATE
WHERE ARRIVAL_DATE = '2026-11-07';