CREATE OR REPLACE TABLE ATMOSYNC_DB.ANALYTICS.IOT_MICROCLIMATE_CLEAN AS
SELECT
    RAW_PAYLOAD:sensor_id::STRING AS SENSOR_ID,
    UPPER(TRIM(RAW_PAYLOAD:market::STRING)) AS MARKET,
    RAW_PAYLOAD:recorded_at::TIMESTAMP_NTZ AS RECORDED_AT,
    DATE(RAW_PAYLOAD:recorded_at::TIMESTAMP_NTZ) AS READING_DATE,
    RAW_PAYLOAD:temp_c::FLOAT AS TEMP_C,
    RAW_PAYLOAD:humidity_pct::FLOAT AS HUMIDITY_PCT,
    RAW_PAYLOAD:storage_zone::STRING AS STORAGE_ZONE,
    INGESTED_AT
FROM ATMOSYNC_DB.RAW.IOT_TELEMETRY;

SELECT * FROM ATMOSYNC_DB.ANALYTICS.IOT_MICROCLIMATE_CLEAN;